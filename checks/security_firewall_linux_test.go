package checks

import (
	"testing"
)

// Docker creates rules in the forward hook and own chains, but does not filter the traffic to the host
const testNftDockerOnly = `{"nftables": [{"metainfo": {"version": "1.1.3", "json_schema_version": 1}},
{"table": {"family": "ip", "name": "filter", "handle": 1}},
{"chain": {"family": "ip", "table": "filter", "name": "INPUT", "handle": 1, "type": "filter", "hook": "input", "prio": 0, "policy": "accept"}},
{"chain": {"family": "ip", "table": "filter", "name": "FORWARD", "handle": 2, "type": "filter", "hook": "forward", "prio": 0, "policy": "drop"}},
{"chain": {"family": "ip", "table": "filter", "name": "DOCKER", "handle": 3}},
{"rule": {"family": "ip", "table": "filter", "chain": "FORWARD", "handle": 10, "expr": []}},
{"rule": {"family": "ip", "table": "filter", "chain": "DOCKER", "handle": 11, "expr": []}}]}`

// firewalld with an accepting policy, the rules of the input hook jump to the zone chains
const testNftFirewalld = `{"nftables": [{"metainfo": {"version": "1.0.9", "json_schema_version": 1}},
{"table": {"family": "inet", "name": "firewalld", "handle": 1}},
{"chain": {"family": "inet", "table": "firewalld", "name": "filter_INPUT", "handle": 1, "type": "filter", "hook": "input", "prio": 10, "policy": "accept"}},
{"rule": {"family": "inet", "table": "firewalld", "chain": "filter_INPUT", "handle": 5, "expr": []}},
{"rule": {"family": "inet", "table": "firewalld", "chain": "filter_INPUT", "handle": 6, "expr": []}},
{"chain": {"family": "netdev", "table": "ingress", "name": "in", "handle": 2, "type": "filter", "hook": "ingress", "prio": 0, "policy": "accept"}}]}`

const testNftDropPolicy = `{"nftables": [
{"chain": {"family": "inet", "table": "filter", "name": "input", "handle": 1, "type": "filter", "hook": "input", "prio": 0, "policy": "drop"}}]}`

func TestParseNftRuleset(t *testing.T) {
	result, err := parseNftRuleset([]byte(testNftDockerOnly))
	if err != nil {
		t.Fatal(err)
	}
	if result.Active || result.InputRules != 0 || result.InputPolicy != "accept" {
		t.Errorf("Docker rules are no host firewall: %+v", result)
	}

	result, err = parseNftRuleset([]byte(testNftFirewalld))
	if err != nil {
		t.Fatal(err)
	}
	if !result.Active || result.InputRules != 2 || result.Backend != "nftables" {
		t.Errorf("unexpected firewalld result: %+v", result)
	}

	result, err = parseNftRuleset([]byte(testNftDropPolicy))
	if err != nil {
		t.Fatal(err)
	}
	if !result.Active || result.InputPolicy != "drop" {
		t.Errorf("unexpected drop policy result: %+v", result)
	}

	if _, err := parseNftRuleset([]byte("Error: Operation not permitted")); err == nil {
		t.Error("expected an error for invalid output")
	}
}

func TestParseIptablesSave(t *testing.T) {
	ufw := `# Generated by iptables-save v1.8.10
*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
:ufw-before-input - [0:0]
-A INPUT -j ufw-before-input
-A INPUT -j ufw-after-input
-A ufw-before-input -i lo -j ACCEPT
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
-A PREROUTING -j DOCKER
COMMIT
`
	result := parseIptablesSave([]byte(ufw))
	if !result.Active || result.InputRules != 2 || result.InputPolicy != "drop" || result.Backend != "iptables" {
		t.Errorf("unexpected ufw result: %+v", result)
	}

	empty := parseIptablesSave([]byte("*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\nCOMMIT\n"))
	if empty.Active || empty.InputRules != 0 {
		t.Errorf("unexpected empty result: %+v", empty)
	}
}
